window.i18n = {
  locale: (function() {
    const saved = localStorage.getItem('language');
    if (saved) return saved;
    const browserLang = (navigator.language || '').split('-')[0].toLowerCase();
    return ['en', 'es'].includes(browserLang) ? browserLang : 'es';
  })(),

  t: function(key, params = {}) {
    const keys = key.split('.');
    let value = translations[this.locale];
    
    for (const k of keys) {
      if (value && value[k]) {
        value = value[k];
      } else {
        // Fallback to Spanish
        let fallbackValue = translations['es'];
        for (const fk of keys) {
          if (fallbackValue && fallbackValue[fk]) {
            fallbackValue = fallbackValue[fk];
          } else {
            return key; // Key not found
          }
        }
        value = fallbackValue;
        break;
      }
    }

    if (typeof value === 'string') {
      return value.replace(/\{\{(\w+)\}\}/g, (_, k) => params[k] || '');
    }
    return key;
  },

  changeLanguage: function(lang) {
    if (['en', 'es'].includes(lang)) {
      this.locale = lang;
      localStorage.setItem('language', lang);
      this.updateDOM();
    }
  },

  updateDOM: function() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.setAttribute('placeholder', this.t(key));
      }
    });
    
    // Dispatch an event so custom scripts know the language changed
    document.dispatchEvent(new Event('languageChanged'));
  },

  init: function() {
    this.updateDOM();
  }
};

// Auto-init on load
document.addEventListener('DOMContentLoaded', () => {
  window.i18n.init();
});
